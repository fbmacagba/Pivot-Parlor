/** GET /api/shops/:slug/services (unwrapped `data` array). */
type ApiPublicService = {
  id: string;
  name: string;
  description?: string;
  durationMinutes: number;
  price_pence: number;
  category?: string;
  image_url?: string | null;
};

export function normalizeCommercialServices(
  rawList: Array<Record<string, unknown>>,
  catalog: string[]
): Service[] {
  return rawList.map((raw, index) => {
    const id = typeof raw.id === "string" ? raw.id : `svc-${index}`;
    const name = String(raw.name ?? "Service");
    const duration_minutes =
      typeof raw.duration_minutes === "number"
        ? raw.duration_minutes
        : typeof raw.duration_min === "number"
          ? raw.duration_min
          : 30;
    const price_gbp =
      typeof raw.price_gbp === "number"
        ? raw.price_gbp
        : typeof raw.price_pence === "number"
          ? raw.price_pence / 100
          : typeof raw.price === "number"
            ? raw.price
            : 0;
    const category =
      (typeof raw.category === "string" && raw.category.trim())
        ? raw.category.trim()
        : "Service";
    const description =
      typeof raw.description === "string" ? raw.description : undefined;
    // Catalog images are positional: catalog[index] is service[index]'s image.
    // A missing or failed image ("" / undefined) falls through to the imageless
    // card variant, so a hole never shifts a later service's photo onto it.
    const image_url =
      typeof raw.image_url === "string"
        ? raw.image_url
        : catalog[index] || "";
    return {
      id,
      name,
      duration_minutes,
      price_gbp,
      category,
      description,
      image_url,
    };
  });
}

export function mapApiServicesToCommercial(
  apiList: ApiPublicService[],
  catalog: string[]
): Service[] {
  return apiList.map((row, index) => ({
    id: row.id,
    name: row.name,
    duration_minutes: row.durationMinutes,
    price_gbp: row.price_pence / 100,
    description: row.description?.trim() || undefined,
    category: row.category?.trim() || "Service",
    // Custom per-service photo wins; else the positional AI pool; else imageless.
    image_url: row.image_url || catalog[index] || "",
  }));
}

/** Normalize `services` from /site (array, JSON string, or missing). */
function parseServicesFromSitePayload(site: ShopSiteData | null): Array<Record<string, unknown>> {
  if (!site) return [];
  const raw = site.services as unknown;
  if (Array.isArray(raw)) {
    return raw.filter((x): x is Record<string, unknown> => x !== null && typeof x === "object");
  }
  if (typeof raw === "string") {
    try {
      const p = JSON.parse(raw) as unknown;
      if (!Array.isArray(p)) return [];
      return p.filter((x): x is Record<string, unknown> => x !== null && typeof x === "object");
    } catch {
      return [];
    }
  }
  return [];
}

export interface ShopSiteData {
  template: string;
  headline: string;
  tagline: string;
  about: string;
  services: Array<Record<string, unknown>>;
  color_primary: string;
  color_accent: string;
  font_heading: string;
  font_body: string;
  hero_image_url: string | null;
  logo_url: string | null;
  catalog_images: string[];
  seo_title?: string | null;
  seo_description?: string | null;
  /** draft | live | paused — public routes gate on this */
  website_status?: string | null;
  /** Per-shop design intent (WS-6) — generated by the research pipeline. */
  trust_signals?: string[];
  usps?: string[];
  layout_mood?: string | null;
  brand_voice?: string | null;
  hero_cta?: string | null;
  about_title?: string | null;
  palette?: Record<string, string> | null;
  design_version?: number | null;
  /** Curated typography (WS-6 item 5). */
  heading_weight?: string | null;
  heading_style?: string | null;
  /** Site Design v3 (Design Director) composition spec — see @repo/utils DesignSpec.
   *  NULL for v1/v2 sites. */
  design_spec?: unknown;
}

export async function loader({ params, context }: LoaderFunctionArgs) {
  const env = context.env as { API_URL: string };
  const api = createApiClient(env.API_URL);
  const slug = params.shopSlug!;

  type ShopPublic = {
    id: string;
    name: string;
    slug: string;
    phone?: string;
    created_at?: string;
  };
  let shop: ShopPublic | null = null;
  try {
    shop = await api.get<ShopPublic>(`/api/shops/${slug}`);
  } catch {
    throw new Response("Shop not found", { status: 404 });
  }

  let site: ShopSiteData | null = null;
  try {
    site = await api.get<ShopSiteData>(`/api/shops/${slug}/site`);
  } catch {
    /* Coming Soon */
  }

  if (site) {
    const ws = (site.website_status ?? "draft").toLowerCase();
    if (ws === "paused") {
      throw new Response(
        `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/><title>Unavailable</title></head><body style="margin:0;font-family:system-ui,sans-serif;background:#111;color:#eee;min-height:100vh;display:flex;align-items:center;justify-content:center;padding:1.5rem;text-align:center"><div><h1 style="font-size:1.25rem;margin:0 0 0.5rem">This site is temporarily unavailable</h1><p style="margin:0;opacity:0.75;font-size:0.95rem">Please try again later.</p></div></body></html>`,
        {
          status: 503,
          headers: { "Content-Type": "text/html; charset=utf-8" },
        }
      );
    }
    if (ws === "draft") {
      throw new Response("Not found", { status: 404 });
    }
  }

  const catalog = site?.catalog_images ?? [];
  let commercialServices: Service[] = [];
  try {
    const apiRows = await api.get<ApiPublicService[]>(`/api/shops/${slug}/services`);
    if (Array.isArray(apiRows) && apiRows.length > 0) {
      commercialServices = mapApiServicesToCommercial(apiRows, catalog);
    }
  } catch {
    /* fall through to shop_sites JSON */
  }

  const siteServicesParsed = parseServicesFromSitePayload(site);
  console.log("[pp shop loader] services from /site after parse", {
    slug,
    count: siteServicesParsed.length,
    names: siteServicesParsed.map((s) => (typeof s.name === "string" ? s.name : "?")),
    rawType: site ? typeof site.services : "no-site",
  });

  if (commercialServices.length === 0 && siteServicesParsed.length > 0) {
    commercialServices = normalizeCommercialServices(siteServicesParsed, catalog);
  }

  const [staffR, reviewsR, settingsR] = await Promise.allSettled([
    api.get<StaffMember[]>(`/api/shops/${slug}/booking-staff`),
    api.get<Review[]>(`/api/shops/${slug}/reviews`),
    api.get<ShopSettings>(`/api/shops/${slug}/settings`),
  ]);

  const staff = staffR.status === "fulfilled" ? staffR.value : [];
  const reviews = reviewsR.status === "fulfilled" ? reviewsR.value : [];
  let settings: ShopSettings = settingsR.status === "fulfilled" ? settingsR.value : {};
  if (shop.phone?.trim() && !settings.phone?.trim()) {
    settings = { ...settings, phone: shop.phone };
  }

  return json({
    slug,
    shop: {
      id: shop.id,
      name: shop.name,
      slug: shop.slug,
      phone: shop.phone,
      created_at: shop.created_at,
    },
    site,
    commercialServices,
    staff,
    reviews,
    settings,
  });
}

export default function ShopLayout() {
  return <Outlet />;
}

// Branded fallback for a missing/unavailable shop or a failed load,
// instead of Remix's default error page.
export function ErrorBoundary() {
  return <ErrorScreen fullscreen />;
}
