// One-off: parse the audit workflow result JSON into docs/AUDIT-2026-06-15.md
import { readFileSync, writeFileSync } from "node:fs";

const SRC = process.argv[2];
const OUT = process.argv[3];

const raw = readFileSync(SRC, "utf8");
const parsed = JSON.parse(raw);
const data = parsed.result ?? parsed; // workflow output wraps the return value under `result`
const { backlog, confirmed = [], counts = {} } = data;

// Index confirmed findings by a normalized title for cross-referencing detail.
const byTitle = new Map();
for (const f of confirmed) {
  if (f && f.title) byTitle.set(f.title.trim().toLowerCase(), f);
}

const sevRank = { critical: 0, high: 1, medium: 2, low: 3 };
const bySev = (a, b) => (sevRank[a.severity] ?? 9) - (sevRank[b.severity] ?? 9);

function detailFor(item) {
  const f = byTitle.get((item.title || "").trim().toLowerCase());
  if (!f) return "";
  const ev = (f.evidence || "").replace(/\n/g, " ").slice(0, 400);
  const notes = (f.verdict?.notes || "").replace(/\n/g, " ").slice(0, 300);
  const lines = [];
  if (f.impact) lines.push(`  - **Impact:** ${f.impact}`);
  if (ev) lines.push(`  - **Evidence:** ${ev}`);
  if (f.effort || f.risk_to_fix) lines.push(`  - **Effort/Risk:** ${f.effort || "?"} / ${f.risk_to_fix || "?"}`);
  if (notes) lines.push(`  - **Verifier:** ${notes}`);
  return lines.length ? "\n" + lines.join("\n") : "";
}

const auto = [...(backlog.autonomous_lane || [])].sort((a, b) => (a.order ?? 99) - (b.order ?? 99));
const signoff = [...(backlog.signoff_lane || [])].sort(bySev);

const stats = backlog.stats || {};
let md = "";
md += `# Pivot Parlor — Platform Audit Backlog (2026-06-15)\n\n`;
md += `> Generated by the multi-dimensional audit workflow (\`pivot-parlor-platform-audit\`, run wf_f540a512-8e6): 7 dimension finders → skeptical adversarial verifier per finding → dedup + two-lane synthesis. This file is the **loop state** — items get checked off as they ship.\n\n`;
md += `**Counts:** ${counts.confirmed ?? "?"} confirmed real (of ${counts.raw ?? "?"} verified; ${counts.rejected ?? "?"} rejected as false positives) → ${auto.length + signoff.length} backlog items.\n`;
md += `**Severity (adjusted):** critical ${stats.critical ?? "?"} · high ${stats.high ?? "?"} · medium ${stats.medium ?? "?"} · low ${stats.low ?? "?"}\n\n`;
md += `## Summary\n\n${backlog.summary || ""}\n\n`;

md += `## Lane policy\n\n`;
md += `- **Autonomous-OK** — behavior-preserving refactors, added tests, dead-code removal. The build + type-check + E2E gate genuinely validates these. The loop ships these without sign-off.\n`;
md += `- **Sign-off required** — auth/security semantics, payment/booking integrity, legal/compliance wording, data-retention/prod-data migrations, subjective visual/UX. The gate CANNOT validate correctness here and several are irreversible on live data. Parked as recommendations; need human approval before shipping.\n\n`;

md += `---\n\n## 🟢 Autonomous lane (${auto.length}) — implement in order\n\n`;
for (const it of auto) {
  md += `- [ ] **${it.id} · ${it.title}** _(${it.severity}, ${it.dimension || "?"}, effort ${it.effort || "?"})_\n`;
  if (it.file) md += `  - \`${it.file}\`\n`;
  md += `  - **Fix:** ${it.recommendation}${detailFor(it)}\n`;
}

md += `\n---\n\n## 🔴 Sign-off lane (${signoff.length}) — need approval before shipping\n\n`;
md += `Sorted by severity. Each needs your go-ahead because the gate can't prove it correct.\n\n`;
let curSev = null;
for (const it of signoff) {
  if (it.severity !== curSev) {
    curSev = it.severity;
    md += `\n### ${String(curSev).toUpperCase()}\n\n`;
  }
  md += `- [ ] **${it.id} · ${it.title}** _(${it.dimension || "?"})_\n`;
  if (it.file) md += `  - \`${it.file}\`\n`;
  md += `  - **Fix:** ${it.recommendation}\n`;
  if (it.why_signoff) md += `  - **Why sign-off:** ${it.why_signoff}${detailFor(it)}\n`;
  else md += detailFor(it).replace(/^\n/, "") + "\n";
}

writeFileSync(OUT, md, "utf8");
console.log(`Wrote ${OUT}: ${auto.length} autonomous, ${signoff.length} signoff`);
// Print the critical + high signoff titles for immediate triage
const urgent = signoff.filter((x) => x.severity === "critical" || x.severity === "high");
console.log("\n=== CRITICAL/HIGH sign-off items ===");
for (const u of urgent) console.log(`${u.severity.toUpperCase().padEnd(8)} ${u.id}  ${u.title}`);
